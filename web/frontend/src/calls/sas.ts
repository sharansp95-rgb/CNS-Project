export async function sas(
  fpA: string,
  fpB: string,
  callId: string,
): Promise<string[]> {
  const [a, b] = [fpA, fpB].map((f) => f.toUpperCase()).sort();
  const digest = await sha(
    concat(
      utf8("securechat/call-sas/v1\0"),
      utf8(a + "\0" + b + "\0" + callId),
    ),
  );
  return Array.from(digest.slice(0, 4), (byte) => WORDS[byte]);
}
